// Writes lib/src/public_suffix_list.dart from the current Public Suffix List.
import 'dart:convert';
import 'dart:io';

import 'package:punycoder/punycoder.dart';

const _source = 'https://publicsuffix.org/list/public_suffix_list.dat';

Future<void> main() async {
  final client = HttpClient();
  final response = await (await client.getUrl(Uri.parse(_source))).close();
  if (response.statusCode != HttpStatus.ok) {
    stderr.writeln('$_source answered ${response.statusCode}');
    exit(1);
  }
  final list = await response.transform(utf8.decoder).join();
  client.close();
  final rules = [
    for (final line in LineSplitter.split(list))
      // A rule ends at the first whitespace.
      if (line.trim().split(RegExp(r'\s')).first case final rule
          when rule.isNotEmpty && !rule.startsWith('//'))
        _ascii(rule),
  ];
  final day = DateTime.now().toUtc().toIso8601String().substring(0, 10);
  final output = File.fromUri(
    Platform.script.resolve('../lib/src/public_suffix_list.dart'),
  );
  await output.writeAsString('''
// Generated by tool/update_public_suffix_list.dart from
// $_source on $day.
//
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.

/// The rules of the Public Suffix List, ICANN and private domains alike, one a
/// line, internationalized labels in punycode.
const publicSuffixRules = r\'\'\'
${rules.join('\n')}
\'\'\';
''');
  print('${rules.length} rules written to ${output.path}');
}

/// Browsers give a page's hostname in punycode.
String _ascii(String rule) {
  final exception = rule.startsWith('!');
  final labels = (exception ? rule.substring(1) : rule).split('.');
  final ascii = [
    for (final label in labels)
      label == '*' ? label : domainToAscii(label, validate: false),
  ];
  return '${exception ? '!' : ''}${ascii.join('.')}';
}
